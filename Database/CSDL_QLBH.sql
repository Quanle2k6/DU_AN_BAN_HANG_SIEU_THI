USE QLBH
GO


CREATE TABLE LOAISP(
    MaLSP CHAR(5) PRIMARY KEY,
    TenLSP NVARCHAR(60) NOT NULL
)
GO

CREATE TABLE SANPHAM(
    MaSP CHAR(5) PRIMARY KEY,
    TenSP NVARCHAR(100) NOT NULL,
    MaLSP CHAR(5) NOT NULL,
    SoLuongCon INT CHECK (SoLuongCon >= 0),
    GiaBan MONEY CHECK (GiaBan > 0),
    CONSTRAINT FK_SP_LSP FOREIGN KEY(MaLSP) REFERENCES LOAISP(MaLSP)
)
GO

CREATE TABLE NHACUNGCAP(
    MaNCC CHAR(5) PRIMARY KEY,
    TenNCC NVARCHAR(50) NOT NULL,
    DiaChi NVARCHAR(100),
    MaSoThue CHAR(10),
    SoTaiKhoan NVARCHAR(20)
)
GO

CREATE TABLE NHAPHANG(
    MaNH CHAR(5) PRIMARY KEY,
    MaNCC CHAR(5) NOT NULL,
    NgGiao SMALLDATETIME,
    NgSX SMALLDATETIME,
    HSD SMALLDATETIME,
    CONSTRAINT FK_NH_NCC FOREIGN KEY(MaNCC) REFERENCES NHACUNGCAP(MaNCC),
    CONSTRAINT CK_NH_DATE CHECK (NgSX < HSD AND NgGiao >= NgSX)
)
GO

CREATE TABLE CHITIETNHAPHANG(
    MaNH CHAR(5),
    MaSP CHAR(5),
    SoLuongNhapHang INT CHECK (SoLuongNhapHang > 0),
    GiaNhap MONEY CHECK (GiaNhap > 0),
    PRIMARY KEY(MaNH, MaSP),
    CONSTRAINT FK_CTNH_NH FOREIGN KEY(MaNH) REFERENCES NHAPHANG(MaNH),
    CONSTRAINT FK_CTNH_SP FOREIGN KEY(MaSP) REFERENCES SANPHAM(MaSP)
)
GO

CREATE TABLE KHUYENMAI(
    MaKM CHAR(5) PRIMARY KEY,
    TenKM NVARCHAR(50),
    NgBD SMALLDATETIME,
    NgKT SMALLDATETIME,
    CONSTRAINT CK_KM_DATE CHECK (NgBD < NgKT)
)
GO

CREATE TABLE NHANVIEN(
    MaNV CHAR(5) PRIMARY KEY,
    TenNV NVARCHAR(100) NOT NULL,
    NgSinh SMALLDATETIME,
    GioiTinh NVARCHAR(5),
    NgBDLamViec SMALLDATETIME,
    Luong MONEY CHECK (Luong > 0),
    CONSTRAINT CK_NV_DATE CHECK (NgBDLamViec >= NgSinh)
)
GO

CREATE TABLE KHACHHANG(
    MaKH CHAR(5) PRIMARY KEY,
    TenKH NVARCHAR(100) NOT NULL,
    DiaChi NVARCHAR(100),
    SDT NVARCHAR(12),
    GioiTinh NVARCHAR(5),
    NgSinh SMALLDATETIME
)
GO


CREATE TABLE HOADON(
    MaHD CHAR(5) PRIMARY KEY,
    MaKH CHAR(5) NOT NULL,
    MaNV CHAR(5) NOT NULL,
    MaKM CHAR(5),
    NgayLapHD SMALLDATETIME NOT NULL DEFAULT GETDATE(),

    ThanhTien MONEY,

    CONSTRAINT FK_HD_KH FOREIGN KEY(MaKH) REFERENCES KHACHHANG(MaKH),
    CONSTRAINT FK_HD_NV FOREIGN KEY(MaNV) REFERENCES NHANVIEN(MaNV),
    CONSTRAINT FK_HD_KM FOREIGN KEY(MaKM) REFERENCES KHUYENMAI(MaKM)
)
GO

CREATE TABLE CTHD(
    MaHD CHAR(5),
    MaSP CHAR(5),
    SoLuongMua INT CHECK (SoLuongMua > 0),
    DonGiaSP MONEY CHECK (DonGiaSP > 0),

    PRIMARY KEY(MaHD, MaSP),

    CONSTRAINT FK_CTHD_HD FOREIGN KEY(MaHD)
        REFERENCES HOADON(MaHD) ON DELETE CASCADE,

    CONSTRAINT FK_CTHD_SP FOREIGN KEY(MaSP)
        REFERENCES SANPHAM(MaSP)
)
GO

CREATE TABLE DANGNHAP(
    TenDN NVARCHAR(100) PRIMARY KEY,
    MatKhau NVARCHAR(50) NOT NULL,
    MaNV CHAR(5) UNIQUE,
    CONSTRAINT FK_DN_NV FOREIGN KEY(MaNV) REFERENCES NHANVIEN(MaNV)
)
GO

